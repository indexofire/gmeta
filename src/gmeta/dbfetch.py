"""`gmeta db fetch` — generate (not run) database download shell scripts.

Reference databases are tens of gigabytes; instead of downloading, gmeta
writes one commented bash script per database target plus a `run_all.sh`.
Users review the URLs (they move with releases), then run the scripts on a
well-connected machine.

Script conventions:

* ``set -euo pipefail``, resumable downloads (``wget -c`` → ``curl -C -``).
* Installs under ``$GMETA_DB_DIR`` (fallback: the value known to gmeta at
  generation time), one sub-directory per tool.
* Each script verifies the layout gmeta's resolvers expect, then hints
  ``gmeta db list``.
"""

from __future__ import annotations

from pathlib import Path

_COMMON_HEADER = """\
#!/usr/bin/env bash
# Generated by `gmeta db fetch` — review before running; URLs move with releases.
set -euo pipefail

DB_ROOT="${GMETA_DB_DIR:-__DB_ROOT__}"

fetch() {
    local url=$1 out=$2
    echo ">> downloading $(basename "$out")"
    if command -v wget >/dev/null 2>&1; then
        wget -c --tries=3 -q --show-progress -O "$out" "$url"
    else
        curl -L -C - --retry 3 -o "$out" "$url"
    fi
}

"""


def _script(body: str, db_root: str) -> str:
    return _COMMON_HEADER.replace("__DB_ROOT__", db_root) + body


def _kraken2(db_root: str) -> str:
    return _script(
        """\
# --- kraken2 + bracken -------------------------------------------------
# MiniKraken2 v2 8GB (RefSeq bacteria/archaea/viral/human + kmer_distrib).
# Alternatives (aws s3, no-sign-request):
#   aws s3 cp --no-sign-request s3://genome-idx/kraken2/k2_standard_16gb_20240925.tar.gz .
#   https://genome-idx.s3.amazonaws.com/kraken2/k2_standard_16gb_20240925.tar.gz
URL="https://genome-idx.gi.ucsc.edu/~alec/kraken/minikraken2_v2_8GB_201904_UPDATE.tgz"

DEST="$DB_ROOT/kraken2"
mkdir -p "$DEST"
fetch "$URL" "$DB_ROOT/minikraken2.tgz"
tar -xzf "$DB_ROOT/minikraken2.tgz" -C "$DB_ROOT"
# tarball extracts into minikraken2_v2_8GB_201904_UPDATE/
if [ -d "$DB_ROOT/minikraken2_v2_8GB_201904_UPDATE" ]; then
    rm -rf "$DEST"
    mv "$DB_ROOT/minikraken2_v2_8GB_201904_UPDATE" "$DEST"
fi
rm -f "$DB_ROOT/minikraken2.tgz"

# bracken needs the kmer_distrib file; warn (not fail) when absent.
if ! ls "$DEST"/database*mers.kmer_distrib >/dev/null 2>&1; then
    echo "WARNING: no databaseXXXmers.kmer_distrib in $DEST — bracken cannot run." >&2
    echo "         Use a database that ships it, or build one with kraken2-build/bracken-build." >&2
fi

test -f "$DEST/hash.k2d" && test -f "$DEST/taxo.k2d"
echo "OK: kraken2 database ready in $DEST — check with: gmeta db list"
""",
        db_root,
    )


def _centrifuge(db_root: str) -> str:
    return _script(
        """\
# --- centrifuge ---------------------------------------------------------
# RefSeq bacteria+archaea compressed index (~6 GB, species-level).
# Other indexes: https://benlangmead.github.io/aws-indexes/centrifuge
URL="https://genome-idx.s3.amazonaws.com/centrifuge/p_compressed_2018_4_15.tar.gz"

DEST="$DB_ROOT/centrifuge"
mkdir -p "$DEST"
fetch "$URL" "$DB_ROOT/centrifuge.tar.gz"
tar -xzf "$DB_ROOT/centrifuge.tar.gz" -C "$DEST"
rm -f "$DB_ROOT/centrifuge.tar.gz"

test -n "$(ls "$DEST"/*.1.cf.index* 2>/dev/null)"
echo "OK: centrifuge index ready in $DEST — check with: gmeta db list"
""",
        db_root,
    )


def _kaiju(db_root: str) -> str:
    return _script(
        """\
# --- kaiju --------------------------------------------------------------
# nr_ezh database (proteins of nr + Euk + giant viruses; includes nodes/names).
# Check https://kaiju.binf.ku.dk/server for newer dated releases.
KAIJU_DB_VERSION="2023-05-23"
URL="https://kaiju.binf.ku.dk/server/kaiju_db_nr_ezh_${KAIJU_DB_VERSION}.tgz"

DEST="$DB_ROOT/kaiju"
mkdir -p "$DEST"
fetch "$URL" "$DB_ROOT/kaiju.tgz"
tar -xzf "$DB_ROOT/kaiju.tgz" -C "$DEST"
rm -f "$DB_ROOT/kaiju.tgz"

test -f "$DEST/nodes.dmp" && test -f "$DEST/names.dmp"
test -n "$(ls "$DEST"/*.fmi 2>/dev/null)"
echo "OK: kaiju database ready in $DEST — check with: gmeta db list"
""",
        db_root,
    )


def _metaphlan(db_root: str) -> str:
    return _script(
        """\
# --- metaphlan ----------------------------------------------------------
# MetaPhlAn installs its own marker database (bowtie2 index, mpa_v*).
# Requires the metaphlan binary (pixi env provides it).
DEST="$DB_ROOT/metaphlan"
mkdir -p "$DEST"

command -v metaphlan >/dev/null 2>&1 || {
    echo "ERROR: metaphlan not on PATH — run inside the gmeta pixi env." >&2
    exit 1
}
metaphlan --install --bowtie2db "$DEST"

test -n "$(ls "$DEST"/mpa_v* 2>/dev/null)" || test -n "$(ls "$DEST"/*.bt2l* 2>/dev/null)"
echo "OK: metaphlan database ready in $DEST — check with: gmeta db list"
""",
        db_root,
    )


def _kmcp(db_root: str) -> str:
    return _script(
        """\
# --- kmcp ---------------------------------------------------------------
# KMCP prebuilt databases ship on OneDrive/CowTransfer (no stable wget URL):
#   https://bioinf.shenwei.me/kmcp/database/
# Download e.g. gtdb.k21-n10.kmcp (Bacteria+Archaea) and extract to:
#   $DB_ROOT/kmcp/
# This script downloads the required NCBI taxdump and waits for the manual
# database copy — re-run it after the manual step to finish verification.

DEST="$DB_ROOT/kmcp"
TAXDUMP="$DB_ROOT/taxdump"
mkdir -p "$DEST" "$TAXDUMP"

if [ ! -d "$TAXDUMP/nodes.dmp" ] && [ ! -f "$TAXDUMP/nodes.dmp" ]; then
    fetch "https://ftp.ncbi.nlm.nih.gov/pub/taxonomy/new_taxdump/new_taxdump.tar.gz" \\
        "$DB_ROOT/new_taxdump.tar.gz"
    tar -xzf "$DB_ROOT/new_taxdump.tar.gz" -C "$TAXDUMP"
    rm -f "$DB_ROOT/new_taxdump.tar.gz"
fi
test -f "$TAXDUMP/nodes.dmp"

if ! find "$DEST" -name '*.uniki' | grep -q .; then
    echo "ACTION REQUIRED: download a prebuilt kmcp database manually" >&2
    echo "  from https://bioinf.shenwei.me/kmcp/database/ (OneDrive/CowTransfer)" >&2
    echo "  and extract it into: $DEST" >&2
    echo "  (expected inside: *.uniki index files + taxid.map)" >&2
    exit 3
fi
test -f "$DEST/taxid.map" || test -n "$(ls "$DEST"/*.map 2>/dev/null)"
echo "OK: kmcp database ready in $DEST (taxdump: $TAXDUMP)"
""",
        db_root,
    )


