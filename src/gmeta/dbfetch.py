def _host(db_root: str) -> str:
    return _script(
        """\
# --- host reference (bowtie2 index for host removal) --------------------
# GRCh38 primary assembly (no alt loci). ~3 GB gz; bowtie2-build ~1h.
URL="https://ftp.ncbi.nlm.nih.gov/genomes/all/GCA/000/001/405/GCA_000001405.29/GRCh38.p14/GCA_000001405.29_GRCh38.p14_genomic.fna.gz"

DEST="$DB_ROOT/host"
mkdir -p "$DEST"
fetch "$URL" "$DEST/GRCh38.fna.gz"

bowtie2-build --threads 8 "$DEST/GRCh38.fna.gz" "$DEST/grch38"
rm -f "$DEST/GRCh38.fna.gz"  # index built; keep the fasta if disk allows

test -f "$DEST/grch38.1.bt2l" || test -f "$DEST/grch38.1.bt2"
echo "OK: host index ready at prefix $DEST/grch38"
echo "     use with: gmeta run ... --host-index $DEST/grch38"
""",
        db_root,
    )


TARGETS: dict[str, object] = {
    "kraken2": _kraken2,
    "centrifuge": _centrifuge,
    "kaiju": _kaiju,
    "metaphlan": _metaphlan,
    "kmcp": _kmcp,
    "sylph": _sylph,
    "taxdump": _taxdump,
    "host": _host,
}

TARGET_HELP = {
    "kraken2": "MiniKraken2 8GB (kraken2 + bracken)",
    "centrifuge": "RefSeq compressed index (~6 GB)",
    "kaiju": "nr_ezh protein database",
    "metaphlan": "MetaPhlAn marker database (via metaphlan --install)",
    "kmcp": "NCBI taxdump + manual prebuilt-db instructions",
    "sylph": "GTDB species sketch (.syldb)",
    "taxdump": "NCBI new_taxdump",
    "host": "GRCh38 + bowtie2 index (host removal)",
}


def write_fetch_scripts(
    targets: list[str],
    out_dir: str | Path,
    db_root: str,
) -> list[Path]:
    """Write ``fetch-<target>.sh`` scripts + a ``run_all.sh``; returns paths."""
    unknown = [t for t in targets if t not in TARGETS]
    if unknown:
        raise ValueError(
            f"unknown fetch target(s): {', '.join(unknown)}; available: {', '.join(TARGETS)}"
        )

    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    written: list[Path] = []
    for target in targets:
        body: str = TARGETS[target](db_root)  # type: ignore[operator]
        script = out / f"fetch-{target}.sh"
        script.write_text(body, encoding="utf-8")
        script.chmod(0o755)
        written.append(script)

    if len(written) > 1:
        lines = [
            "#!/usr/bin/env bash",
            "# Run every generated database fetch script in order. "
            "Each is resumable; kmcp exits 3 until its manual step is done.",
            "set -uo pipefail",
            'here=$(cd "$(dirname "$0")" && pwd)',
            'for s in "$here"/fetch-*.sh; do',
            '    echo "===== $(basename "$s")"',
            '    bash "$s" || echo "WARN: $(basename "$s") did not finish cleanly" >&2',
            "done",
            'echo "all done — verify with: gmeta db list"',
            "",
        ]
        run_all = out / "run_all.sh"
        run_all.write_text("\n".join(lines), encoding="utf-8")
        run_all.chmod(0o755)
        written.append(run_all)
    return written


